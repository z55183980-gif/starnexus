"""Render only the four fixed StarNexus download routes; never reload services."""
import json
import re
from pathlib import Path
from urllib.parse import urlparse

directory = Path(__file__).resolve().parent
manifest = json.loads((directory / 'starnexus-keytool.json').read_text(encoding='utf-8'))
assert set(manifest['releases']) == {'windows', 'macos'}
lines = ['# Generated by render-nginx.py. Include inside the dkby.com server block.',
         '# Update this include and gracefully reload Nginx to change downloads.']
for platform, item in manifest['releases'].items():
    assert re.fullmatch(r'[a-f0-9]{64}', item['sha256'])
    for source, suffix, host in [('primary', '', 'docs.dkby.com'), ('backup', '/github', 'github.com')]:
        target = item[source]
        url = urlparse(target)
        assert url.scheme == 'https' and url.netloc == host and not url.query and not url.fragment
        assert re.fullmatch(r'https://[A-Za-z0-9./_-]+', target), 'Unsafe redirect URL'
        assert url.path.endswith('/' + item['filename'])
        lines.extend([
            'location = /downloads/starnexus-keytool/' + platform + suffix + ' {',
            '    add_header Cache-Control "no-store, max-age=0" always;',
            '    add_header X-Content-Type-Options "nosniff" always;',
            '    return 302 ' + target + ';',
            '}',
        ])
(directory / 'starnexus-keytool.conf').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Rendered four exact download routes for version ' + manifest['version'])
